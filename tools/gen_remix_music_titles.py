#!/usr/bin/env python3
"""Generates port/remix/remix_music_titles_data.inc from the Smash Remix source.

The rows are the track and game titles that BGM.asm string_table shows on VS match start, keyed by Remix BGM id.
Vanilla ids (below midi_count 0x2F) take their track title from the Toggles.asm entry titles, extra ids take it from the
insert_midi / insert_extra_midi calls of midi.asm, numbered in call order from 0x2F.

Usage: python3 tools/gen_remix_music_titles.py <smashremix-src-dir> <output.inc>
"""

import re
import sys
from pathlib import Path

VANILLA_MIDI_COUNT = 0x2F
TRAINING_TITLE = "Training Mode"
MK_HURRY_TITLE = "Mushroom Kingdom (Hurry Up!)"

ADD_GAME_RE = re.compile(r'add_game\((\w+),\s*"([^"]*)"\)')
TOGGLE_TITLE_RE = re.compile(r'entry_random_music_(\w+):;[^\n]*?entry_bool_with_a\("([^"]+)"')
STRING_TABLE_RE = re.compile(r"string_table:\n(.*?)evaluate n\(0x2F\)", re.S)
TABLE_ROW_RE = re.compile(r"^\s*dw\s+(.+?)\s*(?://.*)?$", re.M)
GAME_KEY_RE = re.compile(r"GAME_(\w+)\}")
TOGGLE_REF_RE = re.compile(r"entry_random_music_(\w+)\s*\+\s*0x28")
INSERT_MIDI_RE = re.compile(r'^\s*insert_midi\(\w+,\s*[\w.]+,\s*[\w.]+,\s*"([^"]*)",\s*(\w+),\s*-?\d+\)')
INSERT_NAMED_RE = re.compile(r'^\s*insert_named_extra_midi\(\w+,\s*"([^"]*)",\s*(\w+),\s*-?\d+\)')
INSERT_EXTRA_RE = re.compile(r"^\s*insert_extra_midi\(\w+\)")


def read_source(src_dir, name):
    return (src_dir / name).read_text(encoding="utf-8")


def load_games(midi_text):
    return {key: title for key, title in ADD_GAME_RE.findall(midi_text)}


def load_toggle_titles(toggles_text):
    return {name: title for name, title in TOGGLE_TITLE_RE.findall(toggles_text)}


def vanilla_track_title(cell, toggle_titles):
    toggle = TOGGLE_REF_RE.search(cell)
    if toggle:
        return toggle_titles[toggle.group(1)]
    if "string_training_mode" in cell:
        return TRAINING_TITLE
    if "extra_title_mk" in cell:
        return MK_HURRY_TITLE
    return None


def vanilla_rows(bgm_text, games, toggle_titles):
    block = STRING_TABLE_RE.search(bgm_text).group(1)
    rows = []
    for index, match in enumerate(TABLE_ROW_RE.finditer(block)):
        game_cell, track_cell = split_row(match.group(1))
        game_key = GAME_KEY_RE.search(game_cell)
        game = games[game_key.group(1)] if game_key else None
        track = vanilla_track_title(track_cell, toggle_titles)
        rows.append((index, track, game))
    return rows


def split_row(cells):
    game_cell, _, track_cell = cells.partition(",")
    return game_cell.strip(), track_cell.strip()


def extra_rows(midi_text, games):
    rows = []
    for line in midi_text.splitlines():
        row = extra_row_of(line, games)
        if row is not None:
            rows.append(row)
    return rows


def extra_row_of(line, games):
    named = INSERT_MIDI_RE.match(line) or INSERT_NAMED_RE.match(line)
    if named:
        return named.group(1), games[named.group(2)]
    if INSERT_EXTRA_RE.match(line):
        return None, None
    return None


def build_rows(src_dir):
    midi_text = read_source(src_dir, "midi.asm")
    bgm_text = read_source(src_dir, "BGM.asm")
    toggles_text = read_source(src_dir, "Toggles.asm")
    games = load_games(midi_text)
    toggle_titles = load_toggle_titles(toggles_text)
    vanilla = vanilla_rows(bgm_text, games, toggle_titles)
    if len(vanilla) != VANILLA_MIDI_COUNT:
        sys.exit(f"string_table has {len(vanilla)} rows, expected {VANILLA_MIDI_COUNT}")
    extras = extra_rows(midi_text, games)
    rows = [(index, track, game) for index, track, game in vanilla]
    rows += [(VANILLA_MIDI_COUNT + offset, track, game) for offset, (track, game) in enumerate(extras)]
    return rows


def c_string(text):
    if not text.isascii():
        sys.exit(f"non-ASCII title is not supported by the generator: {text!r}")
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def format_row(index, track, game):
    if track is None or game is None:
        return None
    return f"    {{ 0x{index:02X}, {c_string(track)}, {c_string(game)} }},"


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_remix_music_titles.py <smashremix-src-dir> <output.inc>")
    rows = build_rows(Path(sys.argv[1]))
    lines = [format_row(*row) for row in rows]
    body = [line for line in lines if line is not None]
    header = ["/* Generated by tools/gen_remix_music_titles.py from the Smash Remix source; do not edit. */"]
    Path(sys.argv[2]).write_text("\n".join(header + body) + "\n", encoding="utf-8")
    print(f"wrote {len(body)} rows of {len(rows)} BGM ids to {sys.argv[2]}")


if __name__ == "__main__":
    main()
