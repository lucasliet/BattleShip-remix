#!/usr/bin/env python3
"""Regenerates decomp/src/it/itremix/itremixitems.c.

Collects every `const ITRemixItemDesc dITRemix<Name>ItemDesc` defined in
decomp/src/it/itremix/*.c and lists them in dITRemixItemDescs, the table
itRemixGetItemDesc searches.

Usage: .toolchain/host/venv/bin/python -I tools/gen_remix_items.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ITREMIX_DIR = ROOT / "decomp" / "src" / "it" / "itremix"
OUTPUT = ITREMIX_DIR / "itremixitems.c"
DESC_PATTERN = re.compile(r"^const ITRemixItemDesc (dITRemix\w+ItemDesc)\s*=", re.MULTILINE)


def find_descs() -> list[str]:
    """Returns the descriptor names in path order, so the output is stable."""
    descs = []
    for source in sorted(ITREMIX_DIR.glob("*.c")):
        if source == OUTPUT:
            continue
        descs.extend(DESC_PATTERN.findall(source.read_text()))
    duplicates = {name for name in descs if descs.count(name) > 1}
    if duplicates:
        raise SystemExit(f"duplicate ITRemixItemDesc names: {sorted(duplicates)}")
    return descs


def render(descs: list[str]) -> str:
    """Builds the C source for `descs`."""
    externs = "".join(f"extern const ITRemixItemDesc {name};\n" for name in descs)
    rows = "".join(f"    &{name},\n" for name in descs) or "    NULL,\n"
    count = "ARRAY_COUNT(dITRemixItemDescs)" if descs else "0"
    return (
        "/**\n"
        " * itremixitems.c - every ported Remix custom item.\n"
        " * Generated by tools/gen_remix_items.py; do not edit.\n"
        " */\n\n"
        "#ifdef PORT\n\n"
        '#include "itremix.h"\n\n'
        f"{externs}\n"
        "const ITRemixItemDesc *const dITRemixItemDescs[] =\n{\n"
        f"{rows}"
        "};\n\n"
        f"const s32 dITRemixItemDescsNum = {count};\n\n"
        "#endif\n"
    )


def main() -> int:
    descs = find_descs()
    OUTPUT.write_text(render(descs))
    print(f"{len(descs)} items -> {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
