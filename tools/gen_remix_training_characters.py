#!/usr/bin/env python3
"""Generates port/remix/remix_training_characters_data.inc, the Character entries of the Training per-port chain.

Row order is Training.asm string_table_char (the order of the menu); the name is the db string of the entry label, the id is the
Remix fighter id Training.entry_id_to_char_id gives that entry. The final Random entry is left out, as the menu's own maximum
(char_id_to_entry_id - entry_id_to_char_id - 2) leaves it out.

Inputs: the Remix source dir, build/remixasm/remix.sym and build/remixasm/remix.z64 (scripts/remix/assemble-remix.sh).
Output: only names and numeric ids.

Usage: .toolchain/host/venv/bin/python tools/gen_remix_training_characters.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".toolchain/pkgs/smashremix-src/src/Training.asm"
SYM = ROOT / "build/remixasm/remix.sym"
IMAGE = ROOT / "build/remixasm/remix.z64"
OUT = ROOT / "port/remix/remix_training_characters_data.inc"
IMAGE_RAM = 0x80400000
IMAGE_ROM = 0x02C00000

TABLE_RE = re.compile(r"string_table_char:\n(.*?)\n\s*// @ Description", re.S)
ROW_RE = re.compile(r"^\s*dw\s+(\w+)", re.M)


def load_label_names(text):
    names = {}
    for line in text.splitlines():
        labels = re.findall(r"(\w+):;", line)
        string = re.search(r'db\s+"([^"]*)"', line)
        if string:
            for label in labels:
                names[label] = string.group(1)
    return names


def load_symbol(name):
    for line in SYM.read_text().splitlines():
        address, label = line.split()
        if label == name:
            return int(address, 16)
    sys.exit(f"missing symbol {name} in {SYM}")


def main():
    text = SRC.read_text(encoding="utf-8")
    rows = ROW_RE.findall(TABLE_RE.search(text).group(1))
    names = load_label_names(text)
    ids_at = load_symbol("Training.entry_id_to_char_id") - IMAGE_RAM + IMAGE_ROM
    image = IMAGE.read_bytes()
    entries = rows[:-1]
    lines = ["/* Generated by tools/gen_remix_training_characters.py from the Smash Remix source; do not edit. */"]
    for index, label in enumerate(entries):
        lines.append(f'    {{ {image[ids_at + index]}, "{names[label]}" }},')
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} Training character entries -> {OUT}")


main()
