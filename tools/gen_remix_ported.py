#!/usr/bin/env python3
"""Regenerates decomp/src/ft/ftremix/ftremixported.c.

Collects every `const FTRemixProc dFTRemix<Name>Procs[]` table defined in the
per-fighter directories under decomp/src/ft/ftremix/ and lists them in
dFTRemixPortedProcTables, the tables the action binder searches.

Usage: .toolchain/host/venv/bin/python -I tools/gen_remix_ported.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FTREMIX_DIR = ROOT / "decomp" / "src" / "ft" / "ftremix"
OUTPUT = FTREMIX_DIR / "ftremixported.c"
TABLE_PATTERN = re.compile(r"^const FTRemixProc (dFTRemix\w+Procs)\[\]", re.MULTILINE)


def find_tables() -> list[str]:
    """Returns the table names in path order, so the output is stable."""
    tables = []
    for source in sorted(FTREMIX_DIR.glob("*/*.c")):
        tables.extend(TABLE_PATTERN.findall(source.read_text()))
    duplicates = {name for name in tables if tables.count(name) > 1}
    if duplicates:
        raise SystemExit(f"duplicate FTRemixProc tables: {sorted(duplicates)}")
    return tables


def render(tables: list[str]) -> str:
    """Builds the C source for `tables`."""
    externs = "".join(
        f"extern const FTRemixProc {name}[];\nextern const s32 {name}Num;\n" for name in tables
    )
    rows = "".join(f"    {{ {name}, &{name}Num }},\n" for name in tables)
    return (
        "/**\n"
        " * ftremixported.c - every fighter's table of ported Remix routines.\n"
        " * Generated by tools/gen_remix_ported.py; do not edit.\n"
        " */\n\n"
        "#ifdef PORT\n\n"
        '#include "ftremix.h"\n\n'
        f"{externs}\n"
        "const FTRemixProcTable dFTRemixPortedProcTables[] =\n{\n"
        f"{rows}"
        "};\n\n"
        "const s32 dFTRemixPortedProcTablesNum = ARRAY_COUNT(dFTRemixPortedProcTables);\n\n"
        "#endif\n"
    )


def main() -> int:
    tables = find_tables()
    OUTPUT.write_text(render(tables))
    print(f"{len(tables)} tables -> {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
