#!/usr/bin/env python3
"""Writes decomp/src/gr/grremix/grremixids.h: the Remix stage ids (Stages.asm `scope id`) as C enum constants."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".toolchain/pkgs/smashremix-src/src/Stages.asm"
OUTPUT = ROOT / "decomp/src/gr/grremix/grremixids.h"


def read_stage_ids() -> list:
    lines = SOURCE.read_text().splitlines()
    start = next(n for n, line in enumerate(lines) if re.match(r"\s*scope id \{", line))
    ids = []
    for line in lines[start + 1:]:
        if re.match(r"\s*\}", line):
            break
        match = re.match(r"\s*constant\s+(\w+)\(0x([0-9A-Fa-f]+)\)", line)
        if match:
            ids.append((match.group(1), int(match.group(2), 16)))
    if not ids:
        sys.exit(f"no stage ids found in {SOURCE}")
    return ids


def main() -> None:
    ids = read_stage_ids()
    out = ["/* Generated by tools/gen_remix_stage_ids.py from Stages.asm `scope id`; do not edit. */",
           "#ifndef _GRREMIXIDS_H_", "#define _GRREMIXIDS_H_", "", "typedef enum GRRemixStageId", "{"]
    out += [f"    nGRRemixStage_{name} = 0x{value:02X}," for name, value in ids]
    out += ["", "    nGRRemixStage_End", "", "} GRRemixStageId;", "", "#endif", ""]
    OUTPUT.write_text("\n".join(out))
    print(f"{len(ids)} stage ids -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
